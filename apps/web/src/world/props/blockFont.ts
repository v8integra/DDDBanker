const COLUMNS = 5;
const ROWS = 7;
const ADVANCE = COLUMNS + 1;

export interface BlockTextOptions {
  /** Size of one block in meters. */
  block?: number;
  /** Depth of the letters in meters. */
  depth?: number;
  color: string;
}

/** Width in meters of `text` at the given block size. */
export function blockTextWidth(text: string, block: number) {
  return (text.length * ADVANCE - 1) * block;
}

/**
 * One InstancedMesh (one draw call) spelling `text`, centered on X, with its
 * baseline at y = 0, facing -Z (toward the street).
 */
export function createBlockText(
  text: string,
  { block = 0.12, depth = 0.12, color }: BlockTextOptions,
) {
  const cells: [number, number][] = [];
  [...text.toUpperCase()].forEach((char, index) => {
    const glyph = GLYPHS[char] ?? GLYPHS[' ']!;
    glyph.forEach((row, r) => {
      [...row].forEach((cell, c) => {
        if (cell === '#') cells.push([index * ADVANCE + c, ROWS - 1 - r]);
      });
    });
  });

  // A hair smaller than the grid so neighbors read as chunky blocks with seams.
  const geometry = new THREE.BoxGeometry(block * 0.94, block * 0.94, depth);
  const mesh = new THREE.InstancedMesh(geometry, toon(color), cells.length);
  const offsetX = blockTextWidth(text, block) / 2;
  const matrix = new THREE.Matrix4();
  cells.forEach(([col, row], i) => {
    // Mirror X so text reads left-to-right when viewed from -Z.
    matrix.makeTranslation(offsetX - (col + 0.5) * block, (row + 0.5) * block, 0);
    mesh.setMatrixAt(i, matrix);
  });
  mesh.castShadow = true;
  mesh.name = `sign:${text}`;
  return mesh;
}
